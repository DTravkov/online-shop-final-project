def _start(actor):
    response = actor.post(f"{LINK_PATH}/start")
    assert response.status_code == 200, response.text
    parsed = urlparse(response.json()["url"])
    assert parsed.netloc == "t.me" and parsed.path == "/MintMarketTestBot"
    return parse_qs(parsed.query)["start"][0]


def _redeem(api, start, chat_id):
    envelope = seal(BOT_KEY, json.dumps({"start": start, "chat_id": str(chat_id)}).encode(), BOT_CONTEXT)
    return api.post(f"{BOT_PATH}/redeem", json={"envelope": envelope}, headers=BOT_AUTH)


def _confirm(actor, code):
    return actor.post(f"{LINK_PATH}/confirm", json={"code": code})


def _link(api, actor, chat_id, *, acknowledge=True):
    response = _redeem(api, _start(actor), chat_id)
    assert response.status_code == 200, response.text
    confirmed = _confirm(actor, response.json()["code"])
    assert confirmed.status_code == 204, confirmed.text
    if acknowledge:
        job = _claim(api)
        assert (job["event"], job["chat_id"]) == ("link_success", str(chat_id))
        _report(api, job)


def _claim(api):
    response = api.post(f"{BOT_PATH}/jobs/claim", headers=BOT_AUTH)
    assert response.status_code == 200, response.text
    return response.json()


def _report(api, job, outcome="sent"):
    response = api.post(
        f"{BOT_PATH}/jobs/{job['notification_id']}/result",
        json={"lease_id": job["lease_id"], "outcome": outcome}, headers=BOT_AUTH,
    )
    assert response.status_code == 204, response.text


def test_only_the_mint_market_account_can_confirm_a_one_time_attempt(telegram_api):
    api = telegram_api
    buyer = register_customer(api)
    stranger = register_customer(api, email="stranger@test.local")
    assert buyer.get(LINK_PATH).json() == {"enabled": True, "linked": False}
    assert api.get(LINK_PATH).status_code == 401
    assert login_admin(api).get(LINK_PATH).status_code == 403
    assert buyer.post(f"{BOT_PATH}/jobs/claim").status_code == 401

    old_start = _start(buyer)
    start = _start(buyer)
    assert _redeem(api, old_start, 10001).status_code == 400
    assert _redeem(api, start, -10001).status_code == 400
    code = _redeem(api, start, 10001).json()["code"]
    assert _redeem(api, start, 10002).status_code == 400
    assert _confirm(stranger, code).status_code == 400
    assert buyer.get(LINK_PATH).json()["linked"] is False
    assert _confirm(buyer, code).status_code == 204
    assert buyer.get(LINK_PATH).json()["linked"] is True
    assert _confirm(buyer, code).status_code == 409
    assert _redeem(api, _start(stranger), 10001).status_code == 409

    assert buyer.delete(LINK_PATH).status_code == 204
    assert buyer.delete(LINK_PATH).status_code == 204
    assert buyer.get(LINK_PATH).json()["linked"] is False
    pending = _redeem(api, _start(buyer), 10001).json()["code"]
    assert buyer.delete(LINK_PATH).status_code == 204
    assert _confirm(buyer, pending).status_code == 400
    _link(api, stranger, 10001)


def test_expired_links_cannot_be_redeemed_or_confirmed(telegram_api, monkeypatch):
    from app.service import telegram

    api = telegram_api
    buyer = register_customer(api)
    other_buyer = register_customer(api, email="other@test.local")
    not_started = _start(buyer)
    pending = _redeem(api, _start(other_buyer), 10001).json()["code"]
    current = telegram.datetime

    class Later(current):
        @classmethod
        def now(cls, tz):
            return current.now(tz) + timedelta(minutes=6)

    monkeypatch.setattr(telegram, "datetime", Later)
    assert _redeem(api, not_started, 10001).status_code == 400
    assert _confirm(other_buyer, pending).status_code == 400


def test_two_accounts_cannot_confirm_the_same_chat_concurrently(telegram_api):
    api = telegram_api
    buyer = register_customer(api)
    seller = register_seller(api)
    codes = [_redeem(api, _start(actor), 10001).json()["code"] for actor in (buyer, seller)]
    gate = Barrier(2, timeout=10)

    def confirm(actor, code):
        gate.wait()
        return _confirm(actor, code).status_code

    with ThreadPoolExecutor(max_workers=2) as pool:
        futures = [pool.submit(confirm, actor, code) for actor, code in zip((buyer, seller), codes, strict=True)]
        assert sorted(future.result(timeout=15) for future in futures) == [204, 409]


def test_checkout_and_customer_status_notifications(telegram_api):
    api = telegram_api
    buyer = register_customer(api)
    sellers = [register_seller(api, email=f"seller{index}@test.local") for index in range(3)]
    for index, actor in enumerate([buyer, *sellers]):
        _link(api, actor, 10001 + index)
    products = [add_product(seller) for seller in sellers]

    for product in products:
        assert buyer.post("/customer/cart/items", json={"product_id": product["product_id"]}).status_code == 200
    assert buyer.post("/customer/orders", json={"payment_status": "paid"}).status_code == 400
    assert _claim(api) is None
    placed = buyer.post("/customer/orders")
    assert placed.status_code == 201, placed.text
    order_id = placed.json()["order_id"]
    jobs = []
    for _ in sellers:
        job = _claim(api)
        assert job["event"] == "seller_new_order" and job["order_id"] == order_id
        jobs.append(job["chat_id"])
        _report(api, job)
    assert set(jobs) == {"10002", "10003", "10004"}
    assert _claim(api) is None

    deposit(buyer)
    assert buyer.post(f"/customer/orders/{order_id}/pay").status_code == 200
    job = _claim(api)
    assert (job["event"], job["chat_id"], job["order_id"]) == ("paid", "10001", order_id)
    _report(api, job)
    assert _claim(api) is None
    for seller, status, expected in zip(
        [sellers[0], sellers[1], sellers[2], *sellers],
        ["shipped", "shipped", "shipped", "delivered", "delivered", "delivered"],
        ["partially_shipped", None, "shipped", "partially_delivered", None, "delivered"], strict=True,
    ):
        assert seller.patch(f"/seller/orders/{order_id}/status", json={"order_status": status}).status_code == 200
        job = _claim(api)
        if expected is None:
            assert job is None
        else:
            assert (job["event"], job["chat_id"], job["order_id"]) == (expected, "10001", order_id)
            _report(api, job)

    assert buyer.post("/customer/cart/items", json={"product_id": products[0]["product_id"]}).status_code == 200
    cancelled_id = buyer.post("/customer/orders").json()["order_id"]
    assert buyer.post(f"/customer/orders/{cancelled_id}/cancel").status_code == 200
    assert sellers[0].delete(LINK_PATH).status_code == 204
    job = _claim(api)
    assert (job["event"], job["chat_id"], job["order_id"]) == ("seller_new_order", "10002", cancelled_id)
    _report(api, job)
    job = _claim(api)
    assert (job["event"], job["chat_id"], job["order_id"]) == ("cancelled", "10001", cancelled_id)
    _report(api, job)
    job = _claim(api)
    assert (job["event"], job["chat_id"]) == ("unlink_success", "10002")
    _report(api, job)
    _link(api, sellers[0], 10005)
    assert _claim(api) is None


@pytest.mark.parametrize("role", ["customer", "seller"])
def test_queued_notifications_keep_the_original_chat_after_unlink_and_relink(telegram_api, role):
    api = telegram_api
    buyer = register_customer(api)
    seller = register_seller(api)
    actor = buyer if role == "customer" else seller
    old_chat_id = 4503599627370495
    _link(api, actor, old_chat_id)
    product = add_product(seller)

    def place_and_ship():
        assert buyer.post("/customer/cart/items", json={"product_id": product["product_id"]}).status_code == 200
        placed = buyer.post("/customer/orders")
        assert placed.status_code == 201, placed.text
        order_id = placed.json()["order_id"]
        assert seller.patch(f"/seller/orders/{order_id}/status", json={"order_status": "shipped"}).status_code == 200
        return order_id

    original_order_id = place_and_ship()
    assert actor.delete(LINK_PATH).status_code == 204
    assert actor.delete(LINK_PATH).status_code == 204
    assert actor.get(LINK_PATH).json()["linked"] is False
    place_and_ship()  # Unlinked accounts must not receive new order notifications.
    _link(api, actor, 10002, acknowledge=False)

    job = _claim(api)
    expected_event = "shipped" if role == "customer" else "seller_new_order"
    assert (job["event"], job["chat_id"], job["order_id"]) == (
        expected_event, str(old_chat_id), original_order_id,
    )
    _report(api, job)
    job = _claim(api)
    assert (job["event"], job["chat_id"]) == ("unlink_success", str(old_chat_id))
    _report(api, job)
    job = _claim(api)
    assert (job["event"], job["chat_id"]) == ("link_success", "10002")
    _report(api, job)
    assert _claim(api) is None


def test_chat_order_and_active_leases_survive_link_replacement(telegram_api):
    api = telegram_api
    buyer = register_customer(api)
    seller = register_seller(api)
    _link(api, seller, 10001)
    product = add_product(seller)
    assert buyer.post("/customer/cart/items", json={"product_id": product["product_id"]}).status_code == 200
    assert buyer.post("/customer/orders").status_code == 201
    active_job = _claim(api)
    assert active_job["event"] == "seller_new_order"

    assert seller.delete(LINK_PATH).status_code == 204
    _link(api, buyer, 10001, acknowledge=False)
    assert _claim(api) is None  # The same chat stays blocked until the earlier lease finishes.
    _report(api, active_job)
    for expected_event in ("unlink_success", "link_success"):
        job = _claim(api)
        assert (job["event"], job["chat_id"]) == (expected_event, "10001")
        _report(api, job)
    assert _claim(api) is None


def test_bot_can_reclaim_a_job_and_stale_results_cannot_ack_it(telegram_api, monkeypatch):
    from app.repository import telegram

    api = telegram_api
    buyer = register_customer(api)
    seller = register_seller(api)
    _link(api, seller, 10001)
    product = add_product(seller)
    for _ in range(2):
        assert buyer.post("/customer/cart/items", json={"product_id": product["product_id"]}).status_code == 200
        assert buyer.post("/customer/orders").status_code == 201

    monkeypatch.setattr(telegram, "LEASE_SECONDS", 0)
    first_job = _claim(api)
    monkeypatch.setattr(telegram, "LEASE_SECONDS", 90)
    new_job = _claim(api)
    assert first_job["notification_id"] == new_job["notification_id"]
    assert first_job["lease_id"] != new_job["lease_id"]
    _report(api, first_job)
    assert _claim(api) is None
    _report(api, new_job)
    next_job = _claim(api)
    assert next_job["notification_id"] != new_job["notification_id"]
    _report(api, next_job)
    assert _claim(api) is None
