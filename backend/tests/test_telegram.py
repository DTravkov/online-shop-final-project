def test_encryption_layout_and_context():
    reference = bytes(range(16))
    start = seal(START_KEY, reference, START_CONTEXT)
    assert len(start) == 59
    assert unseal(START_KEY, start, START_CONTEXT) == reference
    assert start != seal(START_KEY, reference, START_CONTEXT)
    with pytest.raises(InvalidTag):
        unseal(START_KEY, start, BOT_CONTEXT)


